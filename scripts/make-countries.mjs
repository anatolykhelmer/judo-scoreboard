#!/usr/bin/env node
// Generates src/data/countries.ts and fills public/flags/ with one SVG per
// country, named by the three-letter IJF code.
//
// Two dev-only sources, joined here so the app needs neither at runtime:
//   - country-data (MIT): IOC three-letter codes and English names.
//   - flag-icons (MIT, https://github.com/lipis/flag-icons): the 4x3 SVGs,
//     named by ISO 3166-1 alpha-2.
//
// Naming the output files by IJF code rather than ISO code is the point of
// the whole script: it means the running app resolves a flag with a template
// string and never carries a code-mapping table of its own.
//
// Run with: node scripts/make-countries.mjs

import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const flagSrcDir = path.join(root, 'node_modules', 'flag-icons', 'flags', '4x3');
const flagOutDir = path.join(root, 'public', 'flags');
const tableOut = path.join(root, 'src', 'data', 'countries.ts');

// The three IJF identities that are not countries. SOR 1.7.2 lets the
// Executive Committee authorise an athlete to compete "under the IJF or a
// neutral flag"; SOR 1.7.2.2 gives the refugee team the code IRT; AIN is the
// IJF's own country page for individual neutral athletes. All three draw the
// federation roundel, which is what ijf.org serves for IJF and IRT.
const NEUTRAL = [
  { code: 'IJF', name: 'Under the IJF flag' },
  { code: 'IRT', name: 'IJF Refugee Team' },
  { code: 'AIN', name: 'Individual Neutral Athletes' },
];

// country-data is from 2015 and still carries the IOC code the country was
// assigned before it renamed. Applied before NAME_OVERRIDES below, so a
// row's name override can key on the code this app actually uses.
const CODE_OVERRIDES = {
  // Swaziland renamed to Eswatini in 2019 and the IOC code became ESW.
  SWZ: 'ESW',
};

// country-data carries ISO's formal names, which read badly in a picker and
// are not what a scoreboard operator calls these places. Sport usage wins.
// Keyed by the code this app uses, i.e. after CODE_OVERRIDES is applied.
const NAME_OVERRIDES = {
  BOL: 'Bolivia',
  CGO: 'Congo',
  COD: 'Congo DR',
  ESW: 'Eswatini',
  FSM: 'Micronesia',
  GBR: 'Great Britain',
  HKG: 'Hong Kong, China',
  IRI: 'Iran',
  ISV: 'Virgin Islands, US',
  IVB: 'Virgin Islands, British',
  KOR: 'Korea',
  LAO: 'Laos',
  MKD: 'North Macedonia',
  PLE: 'Palestine',
  PRK: 'Korea DPR',
  SYR: 'Syria',
  TAN: 'Tanzania',
  TLS: 'Timor-Leste',
  TPE: 'Chinese Taipei',
  VEN: 'Venezuela',
  VIE: 'Vietnam',
  VIN: 'Saint Vincent and the Grenadines',
};

const countryData = JSON.parse(
  readFileSync(path.join(root, 'node_modules', 'country-data', 'data', 'countries.json'), 'utf8'),
);
const available = new Set(
  readdirSync(flagSrcDir).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)),
);

const countries = [];
const missing = [];
for (const c of countryData) {
  // 'user assigned' admits Kosovo (KOS, alpha2 XK): country-data marks it
  // that way rather than 'assigned' because IOC recognition is politically
  // unsettled, but flag-icons ships its flag and this is a judo scoreboard,
  // not an arbiter of statehood — Kosovo won two golds at Tokyo 2020 and an
  // operator must be able to enter its judoka. Ascension Island (SHP) is the
  // only other row this loosening admits, and it still drops out below on
  // the missing-flag path since flag-icons has no file for it.
  if ((c.status !== 'assigned' && c.status !== 'user assigned') || !c.ioc) continue;
  if (!c.alpha2) { missing.push(`${c.ioc} (no alpha2) ${c.name}`); continue; }
  const iso = c.alpha2.toLowerCase();
  if (!available.has(iso)) { missing.push(`${c.ioc} (${iso}) ${c.name}`); continue; }
  const code = CODE_OVERRIDES[c.ioc] ?? c.ioc;
  countries.push({ code, name: NAME_OVERRIDES[code] ?? c.name, iso });
}
countries.sort((a, b) => a.name.localeCompare(b.name, 'en'));

const seen = new Set();
for (const c of countries) {
  if (seen.has(c.code)) throw new Error(`duplicate IJF code: ${c.code}`);
  seen.add(c.code);
}

// Emptied rather than merged: a code dropped upstream must not leave an
// orphan SVG behind that the table no longer mentions.
rmSync(flagOutDir, { recursive: true, force: true });
mkdirSync(flagOutDir, { recursive: true });
for (const c of countries) {
  copyFileSync(path.join(flagSrcDir, `${c.iso}.svg`), path.join(flagOutDir, `${c.code}.svg`));
}

const row = (c) => `  { code: '${c.code}', name: ${JSON.stringify(c.name)}, iso: ${c.iso ? `'${c.iso}'` : 'null'} },`;
const body = `/*
 * Generated by scripts/make-countries.mjs — do not edit by hand.
 *
 * Codes are the three-letter IJF/IOC codes a scoreboard prints. \`iso\` is the
 * ISO 3166-1 alpha-2 code the row's flag was copied from, and null marks the
 * three IJF identities that are not countries at all (see SOR 1.7.2), so
 * "is this neutral" is \`iso === null\` rather than a second field that can
 * disagree with the first.
 *
 * Sources: country-data (IOC codes and names), flag-icons (the artwork).
 */

export interface Country {
  code: string;
  name: string;
  iso: string | null;
}

/** The default for an athlete whose country was not set. SOR 1.7.2's general case. */
export const DEFAULT_COUNTRY = 'IJF';

export const COUNTRIES: Country[] = [
${NEUTRAL.map((c) => row({ ...c, iso: null })).join('\n')}
${countries.map(row).join('\n')}
];
`;

mkdirSync(path.dirname(tableOut), { recursive: true });
writeFileSync(tableOut, body);

console.log(`countries: ${countries.length} + ${NEUTRAL.length} neutral`);
console.log(`flags written to public/flags: ${countries.length}`);
if (missing.length) console.log(`no flag file for:\n  ${missing.join('\n  ')}`);
